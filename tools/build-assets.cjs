// Gzips the dashboard HTML/CSS/JS/service worker from DashboardAssets.h into DashboardAssetsGz.h.
// The ESP32 serves the compressed copies (Content-Encoding: gzip) so the firmware fits the
// 1,310,720-byte OTA slot of the Arduino "Default 4MB" partition scheme.
// Run after editing DashboardAssets.h:  node tools/build-assets.cjs
const fs=require('node:fs'),path=require('node:path'),zlib=require('node:zlib');
const root=path.join(__dirname,'..');
const src=fs.readFileSync(path.join(root,'SmartClassroomS3OLED/DashboardAssets.h'),'utf8').replace(/\r\n/g,'\n');
const names=['DASHBOARD_HTML','DASHBOARD_CSS','DASHBOARD_JS','DASHBOARD_SW'];
let out='#pragma once\n// GENERATED by tools/build-assets.cjs from DashboardAssets.h. Do not edit by hand.\n#include <Arduino.h>\n';
let raw=0,gz=0;
for(const name of names){
  const m=src.match(new RegExp(name+'\\[\\] PROGMEM = R"ASSET\\(([\\s\\S]*?)\\)ASSET";'));
  if(!m)throw Error('asset not found: '+name);
  const data=zlib.gzipSync(Buffer.from(m[1],'utf8'),{level:9});
  raw+=Buffer.byteLength(m[1]);gz+=data.length;
  const lines=[];for(let i=0;i<data.length;i+=24)lines.push(' '+[...data.subarray(i,i+24)].map(b=>'0x'+b.toString(16).padStart(2,'0')).join(','));
  out+=`static const uint8_t ${name}_GZ[] PROGMEM = {\n${lines.join(',\n')}\n};\n`;
}
fs.writeFileSync(path.join(root,'SmartClassroomS3OLED/DashboardAssetsGz.h'),out);
console.log(`dashboard assets: ${raw} bytes -> ${gz} bytes gzip`);
